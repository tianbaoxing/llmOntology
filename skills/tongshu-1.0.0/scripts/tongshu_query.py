def day_ganzhi(year, month, day):
    """日柱干支"""
    base = datetime.date(1899, 1, 1)
    target = datetime.date(year, month, day)
    days = (target - base).days
    idx = (days + 5) % 60
    return tiangan[idx % 10] + dizhi[idx % 12]

def nian_ganzhi(year):
    """年柱干支"""
    tg = tiangan[(year - 4) % 10]
    dz = dizhi[(year - 4) % 12]
    return tg + dz

def get_year_zhi(year):
    """年支"""
    return dizhi[(year - 4) % 12]

def yue_ganzhi(year, month, day):
    """
    月柱干支（简化版，以节气为界）
    使用五虎遁：甲己之年丙作首...
    简化：用农历月近似（实际应以节气为准）
    """
    wuhu_dun = {
        '甲': '丙', '己': '丙',
        '乙': '戊', '庚': '戊',
        '丙': '庚', '辛': '庚',
        '丁': '壬', '壬': '壬',
        '戊': '甲', '癸': '甲'
    }
    
    year_gan = tiangan[(year - 4) % 10]
    first_gan = wuhu_dun[year_gan]
    
    # 月支：正月=寅...
    yue_zhi_map = {
        1: '寅', 2: '卯', 3: '辰', 4: '巳', 5: '午', 6: '未',
        7: '申', 8: '酉', 9: '戌', 10: '亥', 11: '子', 12: '丑'
    }
    
    # 节气→月支映射（节气月建）
    # 小寒→丑, 立春→寅, 惊蛰→卯, 清明→辰, 立夏→巳, 芒种→午, 小暑→未, 立秋→申, 白露→酉, 寒露→戌, 立冬→亥, 大雪→子
    jieqi_list = [
        ((1, 6), '丑'),   # 小寒后为丑月
        ((2, 4), '寅'),   # 立春后为寅月
        ((3, 6), '卯'),   # 惊蛰后为卯月
        ((4, 5), '辰'),   # 清明后为辰月
        ((5, 5), '巳'),   # 立夏后为巳月
        ((6, 5), '午'),   # 芒种后为午月
        ((7, 7), '未'),   # 小暑后为未月
        ((8, 7), '申'),   # 立秋后为申月
        ((9, 7), '酉'),   # 白露后为酉月
        ((10, 8), '戌'),  # 寒露后为戌月
        ((11, 7), '亥'),  # 立冬后为亥月
        ((12, 7), '子'),  # 大雪后为子月
    ]
    
    # 找到最后一个节气<=当前日期的，取其月支
    actual_zhi = '寅'  # 默认
    for (m, d), zhi in jieqi_list:
        if (month, day) >= (m, d):
            actual_zhi = zhi
    
    gan_map = {'甲': 0, '乙': 1, '丙': 2, '丁': 3, '戊': 4,
               '己': 5, '庚': 6, '辛': 7, '壬': 8, '癸': 9}
    
    first_idx = gan_map[first_gan]
    # 月支偏移：从寅月开始算，寅=0, 卯=1, 辰=2, 巳=3, 午=4, 未=5...
    yue_zhi_offset = dizhi.index(actual_zhi) - dizhi.index('寅')
    month_gan = tiangan[(first_idx + yue_zhi_offset) % 10]
    
    return month_gan + actual_zhi

def jianchu_of_date(year, month, day):
    """建除十二神"""
    if year not in JIANCHU_YEAR_ANCHOR:
        return '?'
    
    anchor = JIANCHU_YEAR_ANCHOR[year]
    anchor_dt = datetime.date.fromisoformat(anchor['date'])
    anchor_pos = anchor['pos']
    
    dt = datetime.date(year, month, day)
    days = (dt - anchor_dt).days
    idx = (anchor_pos + days) % 12
    return jianchu[idx]

def ershubu_of_date(year, month, day):
    """二十八宿"""
    if year not in ERSHUBU_YEAR_ANCHOR:
        return '?'
    
    anchor = ERSHUBU_YEAR_ANCHOR[year]
    anchor_dt = datetime.date.fromisoformat(anchor['date'])
    anchor_pos = anchor['pos']
    
    dt = datetime.date(year, month, day)
    days = (dt - anchor_dt).days
    idx = (anchor_pos + days) % 28
    return ershiba[idx]

def shengxiao_of_zhi(zhi):
    """地支对应的生肖"""
    return shengxiao[dizhi.index(zhi)]

def weekday_name(dt):
    """星期"""
    days = ['周一', '周二', '周三', '周四', '周五', '周六', '周日']
    return days[dt.weekday()]

