# ==================== 月历输出 ====================

def print_month_tongshu(year, month):
    """输出整月通书"""
    print("=" * 60)
    print(f"【{year}年{month}月 通书月历】")
    print("=" * 60)
    print(f"{'日期':<12} {'农历':<10} {'干支':<8} {'建除':<4} {'二十八宿':<10} {'吉凶':<4}")
    print("-" * 60)
    
    import calendar
    days_in_month = calendar.monthrange(year, month)[1]
    
    for d in range(1, days_in_month + 1):
        day_gz = day_ganzhi(year, month, d)
        jc = jianchu_of_date(year, month, d)
        es = ershubu_of_date(year, month, d)
        es_xiong = ershiba_jixiong.get(es, '?')
        nongli = get_nongli(year, month, d)
        
        print(f"{year}/{month:02d}/{d:02d} {nongli:<10} {day_gz:<8} {jc:<4} {es:<10} {es_xiong:<4}")

