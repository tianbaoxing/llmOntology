def print_tongshu(year, month, day):
    dt = datetime.date(year, month, day)
    
    year_gz = nian_ganzhi(year)
    yue_gz = yue_ganzhi(year, month, day)
    day_gz = day_ganzhi(year, month, day)
    day_gan = day_gz[0]
    day_zhi = day_gz[1]
    
    jc = jianchu_of_date(year, month, day)
    es = ershubu_of_date(year, month, day)
    es_xiong = ershiba_jixiong.get(es, '?')
    es_mingzu = ershiba_mingzu.get(es, '?')
    es_attr = ershiba_attr.get(es, '?')
    
    cs = chongsha.get(day_zhi, {})
    
    nongli = get_nongli(year, month, day)
    wx = weekday_name(dt)
    
    print("=" * 40)
    print(f"【通书日课】{year}年{month}月{day}日 {wx}")
    print("=" * 40)
    print(f"公历：{year}年{month}月{day}日")
    print(f"农历：{nongli}")
    print(f"干支：{year_gz}年 {yue_gz}月 {day_gz}日")
